"""Render ``report.md`` from a scorecard document."""
from __future__ import annotations

from collections import defaultdict
from typing import Optional

from ..evaluate.scoring import parse_category


def _pct(v: Optional[float]) -> str:
    return "–" if v is None else f"{100 * v:.0f}%"


def _num(v: Optional[float], digits: int = 3) -> str:
    return "–" if v is None else f"{v:.{digits}f}"


def _table(headers: list, rows: list) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def _version_line(tool: str, info: dict) -> str:
    bits = [f"**{tool}**"]
    v = info.get("version")
    if info.get("tag") and info.get("tag") != v:
        bits.append(f"{v} (tag `{info['tag']}`)")
    else:
        bits.append(f"{v}")
    if info.get("commit"):
        bits.append(f"commit `{str(info['commit'])[:12]}`")
    if info.get("image"):
        bits.append(f"image `{info['image']}`")
    if info.get("image_digest"):
        bits.append(f"digest `{str(info['image_digest']).split('@')[-1][:19]}…`")
    rep = info.get("reported") or {}
    if rep.get("name"):
        bits.append(f"self-reported `{rep.get('name')} {rep.get('version') or ''}`".rstrip("` ") + "`")
    comps = info.get("components") or {}
    cq = comps.get("codeql") if isinstance(comps, dict) else None
    if isinstance(cq, dict) and (cq.get("cliVersion") or cq.get("version")):
        bits.append(f"CodeQL `{cq.get('cliVersion') or cq.get('version')}`")
    if isinstance(comps, dict) and comps.get("queryPacks"):
        bits.append("query packs " + ", ".join(f"`{k}@{v}`" for k, v in comps["queryPacks"].items()))
    bits.append(f"resolved {info.get('resolved_at')} via {info.get('source')}")
    return " · ".join(bits)


def render_report(doc: dict) -> str:
    tools = sorted(doc.get("tools") or {})
    scores = doc.get("scores") or {}
    run = doc.get("run") or {}
    baseline = doc.get("baseline") or {}
    lines: list[str] = []
    lines.append(f"# CBOM generator benchmark — run `{run.get('id')}`")
    lines.append("")
    lines.append(f"Generated by cbom-orchestrator {doc.get('orchestrator', {}).get('version')} "
                 f"(scoring model {doc.get('scoringModelVersion')}) on {run.get('finishedAt') or run.get('startedAt')}.")
    lines.append("")
    lines.append("## Ground truth")
    lines.append("")
    lines.append(f"- Corpus: `{baseline.get('repo')}` ref `{baseline.get('ref')}`, commit "
                 f"`{baseline.get('evaluatedCommit') or baseline.get('commit')}`"
                 + (f" (`{baseline.get('evaluatedDescribe')}`)" if baseline.get("evaluatedDescribe") else ""))
    cases = doc.get("cases") or []
    if cases:
        rows = []
        for c in cases:
            st = c.get("stats") or {}
            by = st.get("byType") or {}
            rows.append([c["id"], c.get("language"), f"`{c.get('sourceFile')}`", st.get("assets"), by.get("algorithm", 0),
                         by.get("related-crypto-material", 0), by.get("certificate", 0) + by.get("protocol", 0),
                         by.get("library", 0), st.get("occurrences"), st.get("nonAssetMentions")])
        lines.append("")
        lines.append(_table(["Case", "Language", "Program", "Assets", "Algorithms", "Material", "Cert+Proto", "Libraries",
                             "Occurrences", "Non-asset mentions"], rows))
    lines.append("")
    lines.append("## Tool versions")
    lines.append("")
    for t in tools:
        lines.append(f"- {_version_line(t, doc['tools'][t])}")
        for n in (doc["tools"][t].get("notes") or [])[:3]:
            lines.append(f"  - {n}")
    lines.append("")
    lines.append("## Coverage (run status per language)")
    lines.append("")
    languages = sorted({lang for t in tools for lang in (doc.get("coverage", {}).get(t) or {})})
    rows = [[t] + [doc.get("coverage", {}).get(t, {}).get(lang, "–") for lang in languages] for t in tools]
    lines.append(_table(["Tool"] + languages, rows))
    lines.append("")
    lines.append("## Overall scores")
    lines.append("")
    w = (run.get("config") or {}).get("scoring", {}).get("weights") or {}
    lines.append("Composite score = " + " + ".join(f"{v:.2f}·{k}" for k, v in w.items()) + ".")
    lines.append("")
    rows = []
    for t in tools:
        o = scores.get(t, {}).get("overall") or {}
        rows.append([t, _num(o.get("score")), f"{o.get('detected', 0)}/{o.get('support', 0)}", _pct(o.get("recall")),
                     _pct(o.get("precision")), _pct(o.get("completeness")), _pct(o.get("correctness")), _pct(o.get("locality")),
                     f"{o.get('falsePositives', 0)} ({o.get('lexicalFalsePositives', 0)} lexical)",
                     ", ".join(scores.get(t, {}).get("strengths") or []) or "–"])
    lines.append(_table(["Tool", "Score", "Detected", "Recall", "Precision", "Completeness", "Correctness", "Locality",
                         "False positives", "Strengths (2CBOM)"], rows))
    lines.append("")

    # per-category tables
    for facet, title in (("language", "By language"), ("assetType", "By asset type"), ("subtype", "By primitive / material type"),
                         ("family", "By algorithm family"), ("pqc", "Post-quantum assets")):
        values = sorted({parse_category(k).get(facet) for t in tools for k in scores.get(t, {}).get("byCategory", {})
                         if set(parse_category(k)) == {facet}}, key=str)
        if not values:
            continue
        lines.append(f"## {title}")
        lines.append("")
        lines.append("Each cell: score · recall / precision / correctness (n = ground-truth items).")
        lines.append("")
        rows = []
        for v in values:
            key = f"{facet}={v}"
            row = [str(v)]
            for t in tools:
                agg = scores.get(t, {}).get("byCategory", {}).get(key)
                if not agg:
                    row.append("–")
                else:
                    row.append(f"{_num(agg.get('score'), 2)} · {_pct(agg.get('recall'))}/{_pct(agg.get('precision'))}/"
                               f"{_pct(agg.get('correctness'))} (n={agg.get('support')})")
            rows.append(row)
        lines.append(_table([facet] + tools, rows))
        lines.append("")

    lines.append("## Attribute quality (all categories)")
    lines.append("")
    lines.append("completeness = reported / expected; correctness = correct / reported.")
    lines.append("")
    attrs = sorted({a for t in tools for a in (scores.get(t, {}).get("overall", {}).get("attributes") or {})})
    rows = []
    for a in attrs:
        row = [a]
        for t in tools:
            st = (scores.get(t, {}).get("overall", {}).get("attributes") or {}).get(a)
            row.append("–" if not st else f"{_pct(st.get('completeness'))} / {_pct(st.get('correctness'))} (n={st.get('expected')})")
        rows.append(row)
    lines.append(_table(["Attribute"] + tools, rows))
    lines.append("")

    pw = doc.get("pairwise") or {}
    if pw:
        lines.append("## Head-to-head (overall)")
        lines.append("")
        lines.append("When both tools reported an attribute of the same asset and disagreed, who was right.")
        lines.append("")
        rows = []
        for key, table in sorted(pw.items()):
            a, b = key.split("|", 1)
            agg = (table.get("*") or {}).get("*") or {}
            rows.append([a, b, agg.get("aWins", 0), agg.get("bWins", 0), agg.get("bothWrong", 0), agg.get("agree", 0),
                         agg.get("aOnly", 0), agg.get("bOnly", 0), agg.get("bothMissed", 0)])
        lines.append(_table(["A", "B", "A right", "B right", "both wrong", "agreed", "only A found", "only B found",
                             "both missed"], rows))
        lines.append("")

    # false positive digest
    fps: dict[str, dict] = defaultdict(lambda: defaultdict(int))
    for r in doc.get("ledger") or []:
        if r.get("kind") == "fp":
            fps[r["tool"]][f"{r.get('assetType')}:{r.get('name')}" + (" (lexical)" if r.get("lexical") else "")] += 1
    if fps:
        lines.append("## Most frequent false positives")
        lines.append("")
        for t in tools:
            items = sorted(fps.get(t, {}).items(), key=lambda kv: -kv[1])[:8]
            if items:
                lines.append(f"- **{t}**: " + ", ".join(f"`{k}` ×{n}" for k, n in items))
        lines.append("")

    lines.append("## Run log")
    lines.append("")
    rows = []
    for r in doc.get("runs") or []:
        ev = r.get("evaluation") or {}
        rows.append([r["tool"], r["case"], r.get("status"), _num(r.get("durationSeconds"), 1), ev.get("detections", "–"),
                     f"{ev.get('detectedAssets', '–')}/{ev.get('assets', '–')}", ev.get("unmatched", "–"),
                     (r.get("notes") or [""])[0][:80]])
    lines.append(_table(["Tool", "Case", "Status", "Seconds", "Components", "Assets found", "Unmatched", "Note"], rows))
    lines.append("")
    lines.append("Reconcile a conflict with `orchestrator reconcile <run> --tool-a A --tool-b B --category "
                 "subtype=hash --attribute mode`.")
    return "\n".join(lines) + "\n"
