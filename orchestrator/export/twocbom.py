"""Exports consumed by 2CBOM.

* ``tools.json`` -- a drop-in replacement for ``twocbom/knowledge/tools.json``: ``trust`` is the
  tool's overall benchmark score scaled to 0-100 (clamped to the configured floor/ceiling) and
  ``strengths`` lists the attributes the tool reports reliably.  Tool versions are recorded next to
  each entry so a 2CBOM merge can state which benchmark informed its trust values.
* ``priors.json`` -- the scorecard without the ledger: per-category scores and pairwise head-to-head
  tables, enough for :class:`orchestrator.reconcile.Scorecard` to answer reconciliation queries from the
  precomputed categories when the full ledger is not shipped.
"""
from __future__ import annotations

from typing import Optional

from .. import SCORING_MODEL_VERSION


def _clamp(v: float, lo: float, hi: float) -> int:
    return int(round(max(lo, min(hi, v))))


def build_tools_json(doc: dict, trust_floor: float = 20, trust_ceiling: float = 95, default_trust: float = 50,
                     include_tools: Optional[list] = None) -> dict:
    tools_out = {}
    for tool_id, info in sorted((doc.get("tools") or {}).items()):
        if include_tools and tool_id not in include_tools:
            continue
        spec_tw = (info.get("twocbom") or {})
        scores = (doc.get("scores") or {}).get(tool_id) or {}
        overall = scores.get("overall") or {}
        score = overall.get("score")
        aliases = list(spec_tw.get("aliases") or [tool_id])
        reported = info.get("reported") or {}
        if reported.get("name") and reported["name"].lower() not in [a.lower() for a in aliases]:
            aliases.append(reported["name"])
        entry = {
            "aliases": aliases,
            "trust": _clamp(100.0 * score, trust_floor, trust_ceiling) if score is not None else int(default_trust),
            "detectionMethod": spec_tw.get("detection_method") or "static-source",
            "strengths": list(scores.get("strengths") or []),
            "benchmark": {
                "version": info.get("version"), "tag": info.get("tag"), "commit": info.get("commit"),
                "image": info.get("image"), "imageDigest": info.get("image_digest"),
                "reportedVersion": reported.get("version"), "score": score, "support": overall.get("support"),
                "recall": overall.get("recall"), "precision": overall.get("precision"),
                "completeness": overall.get("completeness"), "correctness": overall.get("correctness"),
                "coverage": scores.get("coverage") or {},
            },
        }
        tools_out[tool_id] = entry
    run = doc.get("run") or {}
    baseline = doc.get("baseline") or {}
    return {
        "$comment": "Generated by cbom-orchestrator from a benchmark against cbomfuse/baseline. 'trust' (0-100) is the "
                    "overall benchmark score; 'strengths' are attributes the tool reports reliably; 'benchmark' records "
                    "the exact tool version that was measured.",
        "version": f"orchestrator-{run.get('id') or 'unknown'}",
        "generated": run.get("finishedAt") or run.get("startedAt"),
        "scoringModelVersion": SCORING_MODEL_VERSION,
        "baseline": {"repo": baseline.get("repo"), "commit": baseline.get("evaluatedCommit") or baseline.get("commit"),
                     "ref": baseline.get("ref")},
        "default": {"trust": int(default_trust), "detectionMethod": "unknown", "strengths": []},
        "tools": tools_out,
    }


def build_priors(doc: dict) -> dict:
    """The scorecard minus the ledger (and minus per-run noise)."""
    keep = ("schemaVersion", "scoringModelVersion", "orchestrator", "run", "baseline", "cases", "tools", "coverage",
            "scores", "pairwise", "summary")
    out = {k: doc[k] for k in keep if k in doc}
    out["ledgerIncluded"] = False
    return out
